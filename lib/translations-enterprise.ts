export const enterpriseTranslations: Record<Locale, Record<string, unknown>> = {
  sk,
  en,
  es,
};

function deepMerge(
  base: Record<string, unknown>,
  extra: Record<string, unknown>
): Record<string, unknown> {
  const result = { ...base };
  for (const key of Object.keys(extra)) {
    const bVal = base[key];
    const eVal = extra[key];
    if (
      bVal &&
      eVal &&
      typeof bVal === "object" &&
      typeof eVal === "object" &&
      !Array.isArray(bVal)
    ) {
      result[key] = deepMerge(
        bVal as Record<string, unknown>,
        eVal as Record<string, unknown>
      );
    } else {
      result[key] = eVal;
    }
  }
  return result;
}

export function mergeTranslations<T extends Record<string, unknown>>(
  base: T,
  locale: Locale
): T {
  return deepMerge(
    base as Record<string, unknown>,
    enterpriseTranslations[locale]
  ) as T;
}
